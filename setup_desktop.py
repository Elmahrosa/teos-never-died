"""Create RAVEN desktop shortcuts.

Resolves the *real* Desktop folder, including OneDrive-redirected Desktops
(where %USERPROFILE%\\Desktop exists but is not what the user sees).

Creates on the Desktop:
    Start_RAVEN_Hidden.vbs   launch RAVEN with no visible window
    Stop_RAVEN.bat           stop only telegram_bot.py
    RAVEN_24_7_Shortcut.lnk  shortcut to the silent launcher
    RAVEN_Config.lnk         open .env in Notepad

Usage:
    python setup_desktop.py            # create shortcuts
    python setup_desktop.py --remove   # delete them again
"""

import os
import sys
import shutil
import subprocess

try:
    from win32com.client import Dispatch

    WIN32_AVAILABLE = True
except ImportError:
    WIN32_AVAILABLE = False

PROJECT_DIR = os.path.dirname(os.path.abspath(__file__))

def get_desktop_path() -> str:
    """Return the Desktop the user actually sees.

    %USERPROFILE%\\Desktop is wrong on OneDrive-redirected profiles, so ask the
    shell for the Known Folder path and fall back sensibly.
    """
    # 1. Ask Windows for the canonical Desktop known folder
    try:
        result = subprocess.run(
            [
                "powershell",
                "-NoProfile",
                "-Command",
                "[Environment]::GetFolderPath('Desktop')",
            ],
            capture_output=True,
            text=True,
            timeout=10,
        )
        path = result.stdout.strip()
        if path and os.path.isdir(path):
            return path
    except Exception:
        pass

    # 2. OneDrive-redirected Desktop
    onedrive = os.getenv("OneDrive") or os.getenv("ONEDRIVE")
    if onedrive:
        candidate = os.path.join(onedrive, "Desktop")
        if os.path.isdir(candidate):
            return candidate

    # 3. Plain profile Desktop
    return os.path.join(os.environ["USERPROFILE"], "Desktop")


def check_project_launchers() -> list:
    """Return the launcher scripts missing from the project folder.

    The project copies are the single source of truth - this script copies
    them to the Desktop rather than duplicating their contents, so the two
    can never drift apart.
    """
    missing = []
    for name in ("Start_RAVEN_Bot.bat", "Stop_RAVEN.bat"):
        if not os.path.isfile(os.path.join(PROJECT_DIR, name)):
            missing.append(name)
    return missing


def desktop_vbs_content() -> str:
    """VBS that launches the project's Start_RAVEN_Bot.bat with no window.

    The project path is baked in, because this copy lives on the Desktop
    while the launcher stays in the project folder. The template uses a
    plain string plus a placeholder because VBScript needs four doubled
    quotes to emit a literal quote, which does not survive an f-string.
    """
    template = (
        "' RAVEN Security Bot - silent launcher (generated by setup_desktop.py)\n"
        "' Launches Start_RAVEN_Bot.bat with no visible window.\n"
        "' No log is written here: VBScript date functions are unreliable on\n"
        "' some regional settings (Now renders as '?', DatePart('mm') is\n"
        "' rejected). The bot's own UTF-8 bot.log is the real audit trail.\n"
        "Option Explicit\n"
        "\n"
        "Dim shell, fso, launcher\n"
        'Set shell = CreateObject("WScript.Shell")\n'
        'Set fso = CreateObject("Scripting.FileSystemObject")\n'
        'launcher = "@LAUNCHER@"\n'
        "If Not fso.FileExists(launcher) Then\n"
        '    MsgBox "Start_RAVEN_Bot.bat not found:" & vbCrLf & launcher, vbCritical, "RAVEN"\n'
        "    WScript.Quit 1\n"
        "End If\n"
        "shell.CurrentDirectory = fso.GetParentFolderName(launcher)\n"
        "' 0 = hidden window, False = do not wait for it to finish\n"
        'shell.Run """" & launcher & """", 0, False\n'
    )
    bat = os.path.join(PROJECT_DIR, "Start_RAVEN_Bot.bat")
    return template.replace("@LAUNCHER@", bat)


def make_shortcut(shortcut_path: str, target: str, description: str, icon: str = None) -> str:
    """Create a .lnk via the Windows shell. Returns the path."""
    if not WIN32_AVAILABLE:
        print("  [!] pywin32 not installed - skipping shortcut (pip install pywin32)")
        return None
    shell = Dispatch("WScript.Shell")
    shortcut = shell.CreateShortCut(shortcut_path)
    shortcut.Targetpath = target
    shortcut.WorkingDirectory = os.path.dirname(target) if os.path.isfile(target) else PROJECT_DIR
    shortcut.Description = description
    shortcut.IconLocation = icon or "shell32.dll,13"
    shortcut.save()
    return shortcut_path


def create(desktop_path: str) -> int:
    """Create all Desktop entries."""
    print("Creating RAVEN desktop shortcuts...")

    print("\n  Project launchers")
    missing = check_project_launchers()
    if missing:
        print(f"    [X] missing from the project folder: {', '.join(missing)}")
        print("        Restore them before using the Desktop shortcuts.")
        return 1
    for name in ("Start_RAVEN_Bot.bat", "Stop_RAVEN.bat"):
        print(f"    [OK] {name}")

    print(f"\n  Desktop: {desktop_path}")
    if not os.path.isdir(desktop_path):
        os.makedirs(desktop_path, exist_ok=True)
        print("    (created - this Desktop folder did not exist yet)")

    # Silent launcher: generated, because it must point at the project folder
    vbs_path = os.path.join(desktop_path, "Start_RAVEN_Hidden.vbs")
    with open(vbs_path, "w", encoding="utf-8") as handle:
        handle.write(desktop_vbs_content())
    print(f"    [OK] {os.path.basename(vbs_path)}")

    # Stop script: verbatim copy of the project version
    bat_path = os.path.join(desktop_path, "Stop_RAVEN.bat")
    shutil.copyfile(os.path.join(PROJECT_DIR, "Stop_RAVEN.bat"), bat_path)
    print(f"    [OK] {os.path.basename(bat_path)}")

    lnk = make_shortcut(
        os.path.join(desktop_path, "RAVEN_24_7_Shortcut.lnk"),
        vbs_path,
        "Start RAVEN silently",
    )
    if lnk:
        print(f"    [OK] {os.path.basename(lnk)}")

    env_file = os.path.join(PROJECT_DIR, ".env")
    if os.path.isfile(env_file):
        cfg = make_shortcut(
            os.path.join(desktop_path, "RAVEN_Config.lnk"),
            env_file,
            "Edit RAVEN configuration",
        )
        if cfg:
            print(f"    [OK] {os.path.basename(cfg)}")
    else:
        print("    [--] .env not found - skipped RAVEN_Config.lnk")

    print("\nDone.")
    print("  Start : double-click 'Start_RAVEN_Hidden.vbs' or RAVEN_24_7_Shortcut.lnk")
    print("  Stop  : double-click 'Stop_RAVEN.bat' (only stops telegram_bot.py)")
    print("  Logs  : bot.log in the project folder")
    return 0


def remove(desktop_path: str) -> int:
    """Delete the entries this script created."""
    print("Removing RAVEN desktop shortcuts...")
    for name in (
        "Start_RAVEN_Hidden.vbs",
        "Stop_RAVEN.bat",
        "RAVEN_24_7_Shortcut.lnk",
        "RAVEN_Config.lnk",
    ):
        path = os.path.join(desktop_path, name)
        if os.path.exists(path):
            os.remove(path)
            print(f"    [OK] removed {name}")
        else:
            print(f"    [--] {name} not present")
    return 0


def main() -> int:
    desktop_path = get_desktop_path()
    try:
        if "--remove" in sys.argv:
            return remove(desktop_path)
        return create(desktop_path)
    except Exception as exc:
        print(f"ERROR: {exc}")
        return 1


if __name__ == "__main__":
    sys.exit(main())
